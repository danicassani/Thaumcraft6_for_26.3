package thaumcraft.config;

import net.minecraftforge.common.ForgeConfigSpec;

/** Verified legacy defaults; gameplay consumers are deferred to later ports. */
public final class ThaumcraftConfig {
    private ThaumcraftConfig() {}
    public static final ForgeConfigSpec CLIENT;
    public static final ForgeConfigSpec SERVER;
    public static final ForgeConfigSpec.BooleanValue largeTagText;
    public static final ForgeConfigSpec.BooleanValue disableShaders;
    public static final ForgeConfigSpec.BooleanValue crooked;
    public static final ForgeConfigSpec.BooleanValue nostress;
    public static final ForgeConfigSpec.BooleanValue dialBottom;
    public static final ForgeConfigSpec.BooleanValue showTags;
    public static final ForgeConfigSpec.BooleanValue blueBiome;
    public static final ForgeConfigSpec.BooleanValue showGolemEmotes;
    public static final ForgeConfigSpec.IntValue oreDensity;
    public static final ForgeConfigSpec.BooleanValue generateMagicForest;
    public static final ForgeConfigSpec.IntValue biomeMagicalForestWeight;
    public static final ForgeConfigSpec.DoubleValue taintSpreadRate;
    public static final ForgeConfigSpec.IntValue taintSpreadArea;
    public static final ForgeConfigSpec.BooleanValue generateAura;
    public static final ForgeConfigSpec.BooleanValue generateFluxRifts;
    public static final ForgeConfigSpec.BooleanValue generateStructure;
    public static final ForgeConfigSpec.BooleanValue generateCinnabar;
    public static final ForgeConfigSpec.BooleanValue generateAmber;
    public static final ForgeConfigSpec.BooleanValue generateQuartz;
    public static final ForgeConfigSpec.BooleanValue generateCrystals;
    public static final ForgeConfigSpec.BooleanValue generateTrees;
    public static final ForgeConfigSpec.ConfigValue<String> regenKey;
    public static final ForgeConfigSpec.BooleanValue regenAura;
    public static final ForgeConfigSpec.BooleanValue regenStructure;
    public static final ForgeConfigSpec.BooleanValue regenCinnabar;
    public static final ForgeConfigSpec.BooleanValue regenAmber;
    public static final ForgeConfigSpec.BooleanValue regenQuartz;
    public static final ForgeConfigSpec.BooleanValue regenCrystals;
    public static final ForgeConfigSpec.BooleanValue regenTrees;
    public static final ForgeConfigSpec.BooleanValue allowSpawnAngryZombie;
    public static final ForgeConfigSpec.BooleanValue allowSpawnFireBat;
    public static final ForgeConfigSpec.BooleanValue allowSpawnWisp;
    public static final ForgeConfigSpec.BooleanValue allowSpawnTaintacle;
    public static final ForgeConfigSpec.BooleanValue allowSpawnPech;
    public static final ForgeConfigSpec.BooleanValue allowSpawnElder;
    public static final ForgeConfigSpec.BooleanValue allowChampionMobs;
    public static final ForgeConfigSpec.BooleanValue noSleep;
    public static final ForgeConfigSpec.BooleanValue wussMode;
    public static final ForgeConfigSpec.BooleanValue allowCheatSheet;
    public static final ForgeConfigSpec.IntValue shieldRecharge;
    public static final ForgeConfigSpec.IntValue shieldWait;
    public static final ForgeConfigSpec.IntValue shieldCost;
    static {
        var client = new ForgeConfigSpec.Builder();
        var server = new ForgeConfigSpec.Builder();
        client.push("graphics");
        largeTagText = client.define("largeTagText", false);
        disableShaders = client.define("disableShaders", false);
        crooked = client.define("crooked", true);
        nostress = client.define("nostress", false);
        dialBottom = client.define("dialBottom", false);
        showTags = client.define("showTags", false);
        blueBiome = client.define("blueBiome", false);
        client.pop();
        server.push("graphics");
        showGolemEmotes = server.define("showGolemEmotes", true);
        server.pop();
        server.push("world");
        oreDensity = server.worldRestart().defineInRange("oreDensity", 100, 1, 500);
        generateMagicForest = server.define("generateMagicForest", true);
        biomeMagicalForestWeight = server.worldRestart().defineInRange("biomeMagicalForestWeight", 5, 0, 100);
        taintSpreadRate = server.defineInRange("taintSpreadRate", 100.0, 0, 500);
        taintSpreadArea = server.defineInRange("taintSpreadArea", 32, 8, 256);
        generateAura = server.define("generateAura", true);
        generateFluxRifts = server.comment("Allow excessive flux to spawn rifts in loaded chunks.").define("generateFluxRifts", true);
        generateStructure = server.define("generateStructure", true);
        generateCinnabar = server.define("generateCinnabar", true);
        generateAmber = server.define("generateAmber", true);
        generateQuartz = server.define("generateQuartz", true);
        generateCrystals = server.define("generateCrystals", true);
        generateTrees = server.define("generateTrees", true);
        regenKey = server.define("regenKey", "DEFAULT");
        regenAura = server.define("regenAura", false);
        regenStructure = server.define("regenStructure", false);
        regenCinnabar = server.define("regenCinnabar", false);
        regenAmber = server.define("regenAmber", false);
        regenQuartz = server.define("regenQuartz", false);
        regenCrystals = server.define("regenCrystals", false);
        regenTrees = server.define("regenTrees", false);
        allowSpawnAngryZombie = server.define("allowSpawnAngryZombie", true);
        allowSpawnFireBat = server.define("allowSpawnFireBat", true);
        allowSpawnWisp = server.define("allowSpawnWisp", true);
        allowSpawnTaintacle = server.define("allowSpawnTaintacle", true);
        allowSpawnPech = server.define("allowSpawnPech", true);
        allowSpawnElder = server.define("allowSpawnElder", true);
        allowChampionMobs = server.define("allowChampionMobs", true);
        server.pop();
        server.push("misc");
        noSleep = server.define("noSleep", false);
        wussMode = server.define("wussMode", false);
        allowCheatSheet = server.define("allowCheatSheet", false);
        shieldRecharge = server.defineInRange("shieldRecharge", 2000, 500, 500000);
        shieldWait = server.defineInRange("shieldWait", 4000, 0, 50000);
        shieldCost = server.defineInRange("shieldCost", 1, 0, 500);
        server.pop();
        CLIENT = client.build();
        SERVER = server.build();
    }
}
