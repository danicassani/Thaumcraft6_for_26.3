#!/usr/bin/env python3
"""Translate TC6 guardian's original box definitions and rest poses to native model parts."""
import re
from pathlib import Path
R=Path(__file__).resolve().parents[1]
s=(R/'src/main/java/thaumcraft/client/renderers/models/entity/ModelEldritchGuardian.java').read_text()
parts=[]
num=lambda a:float(a.strip().rstrip('fFdD'))
for m in re.finditer(r'\((\w+) = new ModelRenderer\(this, (\d+), (\d+)\)\)\.addBox\(([^;]+)\);',s):
 n,u,v,box=m.groups();values=list(map(num,box.split(',')));pos=re.search(r'\b'+n+r'\.setRotationPoint\(([^)]+)\)',s);rot=re.search(r'setRotation\('+n+r', ([^)]+)\)',s);parts.append((n,u,v,values,list(map(num,pos[1].split(','))) if pos else [0,0,0],list(map(num,rot[1].split(','))) if rot else [0,0,0]))
assert len(parts)>45,len(parts)
F=lambda v:f'{float(v)}F'
lines=['package thaumcraft.client;','import net.minecraft.client.model.geom.builders.*;','import net.minecraft.client.model.geom.PartPose;','/** Original TC6 guardian geometry; generated by tools/generate_warp_models.py. */','public final class WarpGuardianGeometry {',' public static LayerDefinition layer(){var mesh=new MeshDefinition();var root=mesh.getRoot();']
parents={child:parent for parent,child in re.findall(r'(\w+)\.addChild\((\w+)\)',s)}
assert len({p[0] for p in parts})==len(parts)
assert set(parents)|set(parents.values()) <= {p[0] for p in parts}
# Parents precede descendants in the legacy constructor.
for n,u,v,box,pos,rot in parts:
 parent='root' if n not in parents else 'part_'+parents[n]
 lines.append(' var part_'+n+'='+parent+'.addOrReplaceChild("'+n+'",CubeListBuilder.create().texOffs('+u+','+v+').addBox('+','.join(map(F,box))+'),PartPose.offsetAndRotation('+','.join(map(F,pos+rot))+'));')
lines+=[' return LayerDefinition.create(mesh,128,64);}','}']
(R/'src/modern/java/thaumcraft/client/WarpGuardianGeometry.java').write_text('\n'.join(lines)+'\n')
print('Original guardian model:',len(parts),'boxes')
